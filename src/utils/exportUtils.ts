import { Dataset, EdaReport, TrainedModel } from '../types';

export function exportDatasetToCsv(dataset: Dataset): void {
  const headers = dataset.columns.map((c) => c.name);
  const rows = dataset.rows.map((row) => {
    return headers
      .map((col) => {
        const val = row[col];
        if (val === null || val === undefined) return '';
        const str = String(val).replace(/"/g, '""');
        return `"${str}"`;
      })
      .join(',');
  });

  const csvContent = [headers.join(','), ...rows].join('\n');
  downloadBlob(
    csvContent,
    `${dataset.name.toLowerCase().replace(/\s+/g, '_')}_export.csv`,
    'text/csv;charset=utf-8;'
  );
}

export function exportDatasetToJson(dataset: Dataset): void {
  const jsonContent = JSON.stringify(dataset.rows, null, 2);
  downloadBlob(
    jsonContent,
    `${dataset.name.toLowerCase().replace(/\s+/g, '_')}_export.json`,
    'application/json;charset=utf-8;'
  );
}

export function generateMarkdownReport(
  dataset: Dataset,
  eda?: EdaReport | null,
  model?: TrainedModel | null
): string {
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let md = `# DATAFORGE - TECHNICAL DATA AUDIT REPORT\n\n`;
  md += `**Document Version:** 1.0.0  \n`;
  md += `**Generated At:** ${dateStr}  \n`;
  md += `**Dataset Provenance:** ${dataset.name} (${dataset.format.toUpperCase()}, ${dataset.rowCount} rows, ${dataset.columnCount} columns)  \n`;
  md += `**Data Integrity Score:** ${dataset.qualityScore}/100  \n\n`;

  md += `## 1. Executive Summary\n\n`;
  if (eda?.executiveSummary) {
    md += `${eda.executiveSummary}\n\n`;
  } else {
    md += `Comprehensive evaluation of '${dataset.name}' completed across data validation, schema enforcement, exploratory statistics, and predictive modeling pipelines.\n\n`;
  }

  md += `## 2. Dataset Schema & Validation Health\n\n`;
  md += `| Column Name | Inferred Type | Nullable | Completeness |\n`;
  md += `| :--- | :--- | :--- | :--- |\n`;
  dataset.columns.forEach((col) => {
    md += `| \`${col.name}\` | ${col.type} | ${col.nullable ? 'Yes' : 'No'} | ${dataset.qualityScore}% |\n`;
  });
  md += `\n`;

  if (eda && eda.summaryStats.length > 0) {
    md += `## 3. Exploratory Data Profiling\n\n`;
    md += `| Attribute | Count | Missing % | Mean | Median | Std Dev | Min | Max |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
    eda.summaryStats.forEach((st) => {
      md += `| \`${st.column}\` | ${st.count} | ${st.missingPercentage}% | ${st.mean ?? 'N/A'} | ${st.median ?? 'N/A'} | ${st.stdDev ?? 'N/A'} | ${st.min ?? 'N/A'} | ${st.max ?? 'N/A'} |\n`;
    });
    md += `\n`;
  }

  if (model) {
    md += `## 4. Statistical Model Benchmark\n\n`;
    md += `- **Algorithm:** ${model.algorithm}\n`;
    md += `- **Target Feature:** \`${model.targetFeature}\`\n`;
    md += `- **Predictors:** ${model.predictorFeatures.map((f) => `\`${f}\``).join(', ')}\n`;
    md += `- **Training Time:** ${model.metrics.trainingTimeSec}s\n`;
    md += `- **Inference Latency:** ${model.metrics.inferenceLatencyMs}ms\n\n`;

    md += `### Metrics Performance\n\n`;
    if (model.metrics.accuracy !== undefined) {
      md += `- **Accuracy:** ${(model.metrics.accuracy * 100).toFixed(2)}%\n`;
      md += `- **Precision:** ${(model.metrics.precision! * 100).toFixed(2)}%\n`;
      md += `- **Recall:** ${(model.metrics.recall! * 100).toFixed(2)}%\n`;
      md += `- **F1-Score:** ${model.metrics.f1Score}\n`;
      md += `- **ROC-AUC:** ${model.metrics.rocAuc}\n`;
    } else if (model.metrics.r2Score !== undefined) {
      md += `- **R-Squared (R2):** ${model.metrics.r2Score}\n`;
      md += `- **MAE:** ${model.metrics.mae}\n`;
      md += `- **RMSE:** ${model.metrics.rmse}\n`;
    }
    md += `\n`;

    if (model.featureImportance && model.featureImportance.length > 0) {
      md += `### Feature Importance Hierarchy\n\n`;
      model.featureImportance.forEach((fi, idx) => {
        md += `${idx + 1}. **${fi.feature}**: ${(fi.importance * 100).toFixed(1)}%\n`;
      });
      md += `\n`;
    }
  }

  md += `## 5. Governance & Operational Recommendations\n\n`;
  md += `1. **Continuous Drift Monitoring:** Enable daily Population Stability Index (PSI) checks to detect covariate shift.\n`;
  md += `2. **Automated Pipeline Scheduling:** Maintain cron executions for feature store refresh.\n`;
  md += `3. **Model Version Tagging:** Ensure candidate models are validated against the Staging baseline before production rollout.\n\n`;
  md += `---\n*Generated by DATAFORGE Platform*\n`;

  return md;
}

export function downloadBlob(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
